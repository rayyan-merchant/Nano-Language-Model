"""Regenerate only application metadata from immutable accepted research records."""
import json
from pathlib import Path
from api.catalog import catalog


def main():
    path=Path(__file__).resolve().parents[1]/'frontend/lib/research.json'
    value={'source':'Accepted research manifests; generated by tools.sync_research',
           'models':[{**v,'availability':'unavailable'} for v in catalog().values()]}
    path.write_text(json.dumps(value,indent=2)+'\n',encoding='utf-8')


if __name__=='__main__':main()
