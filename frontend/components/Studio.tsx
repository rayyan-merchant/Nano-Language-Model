"use client";
import { useEffect, useRef, useState } from "react";
import {
  api,
  type Comparison,
  type Generation,
  type Model,
  type ModelID,
  type Settings,
} from "@/lib/api";
import evidence from "@/lib/research.json";
const prompts = [
  "To be, or not to be",
  "ROMEO:\n",
  "JULIET:\n",
  "First Citizen:\n",
  "The king",
];
const staticModels = evidence.models as Model[];
function Output({
  result,
  model,
  busy,
  loading,
  error,
}: {
  result?: Generation;
  model: Model;
  busy: boolean;
  loading?: boolean;
  error?: string;
}) {
  const [copied, setCopied] = useState(false),
    [copyError, setCopyError] = useState(false);
  async function copy() {
    try {
      await navigator.clipboard.writeText(result!.full_output);
      setCopied(true);
      setTimeout(() => setCopied(false), 1800);
    } catch {
      setCopyError(true);
    }
  }
  return (
    <article className="output">
      <div className="output-head">
        <span className="eyebrow">
          {model.name} · {model.id.toUpperCase()}
        </span>
        {result && (
          <button className="text-button" onClick={copy}>
            {copied ? "Copied ✓" : "Copy output ↗"}
          </button>
        )}
      </div>
      {busy ? (
        <div className="waiting" role="status">
          <span className="spinner" />
          <h3>{loading ? 'Preparing the verified model.' : 'Finding the next word.'}</h3>
          <p>{loading ? 'Cold start: weights are loaded and checked before inference.' : 'Real inference, one token at a time.'}</p>
        </div>
      ) : error ? (
        <div className="empty error" role="alert">
          <h3>The page can wait.</h3>
          <p>{error}</p>
        </div>
      ) : result ? (
        <>
          <pre className="generated">
            {result.full_output.split("\n").map((line, index, lines) => (
              <span
                key={index}
                className={
                  /^[A-Za-z][A-Za-z '\-]{0,48}:$/.test(line)
                    ? "speaker"
                    : undefined
                }
              >
                {line}
                {index < lines.length - 1 ? "\n" : ""}
              </span>
            ))}
          </pre>
          <div className="output-meta">
            <span>{result.generated_tokens} new tokens</span>
            <span>{result.latency_seconds.toFixed(2)} s</span>
            <span>
              Seed {result.seed} ·{" "}
              {result.settings.greedy ? "greedy" : "sampling"}
            </span>
            <span>Temperature {String(result.settings.temperature)} · limit {String(result.settings.max_new_tokens)} tokens</span>
          </div>
          {result.context_cropped && (
            <p className="note">
              Only the latest {result.effective_context} prompt tokens
              conditioned the first prediction.
            </p>
          )}
          {result.replacement_characters && (
            <p className="note">
              Some generated bytes were invalid UTF-8 and appear as �. Output is
              unedited.
            </p>
          )}
          {copyError && (
            <p role="alert">
              Clipboard unavailable. Select the text to copy it.
            </p>
          )}
        </>
      ) : (
        <div className="empty">
          <span className="quill" aria-hidden="true">
            ❧
          </span>
          <h3>A stage for your next line.</h3>
          <p>
            Begin with a thought. Let a small model carry it somewhere
            unexpected.
          </p>
          <span className="empty-rule" />
          <small>
            Authentic output will appear here.
            <br />
            Nothing has been generated yet.
          </small>
        </div>
      )}
    </article>
  );
}
export default function Studio({ compare = false }: { compare?: boolean }) {
  const [models, setModels] = useState(staticModels),
    [connection, setConnection] = useState("checking"),
    [selected, setSelected] = useState<ModelID>("b01");
  const [settings, setSettings] = useState<Settings>({
    prompt: "ROMEO:\n",
    max_new_tokens: 128,
    temperature: 0.7,
    seed: 42,
    greedy: false,
  });
  const [result, setResult] = useState<Generation>(),
    [comparison, setComparison] = useState<Comparison>(),
    [state, setState] = useState("idle"),
    [error, setError] = useState("");
  const abort = useRef<AbortController | null>(null);
  const serial = useRef(0);
  const pollTimer = useRef<ReturnType<typeof setInterval> | null>(null);
  async function refresh() {
    try {
      const value = await api.models();
      setModels(value.models);
      setConnection("connected");
    } catch {
      setConnection("offline");
    }
  }
  useEffect(() => {
    refresh();
    return () => {
      abort.current?.abort();
      if (pollTimer.current) clearInterval(pollTimer.current);
    };
  }, []);
  async function submit() {
    const id = ++serial.current;
    abort.current?.abort();
    const controller = new AbortController();
    abort.current = controller;
    const needsLoad = models.some(m => (compare || m.id === selected) && m.availability === 'not_loaded');
    setState(needsLoad ? 'loading' : 'generating');
    const polling = setInterval(async () => {
      try {
        const value = await api.models(controller.signal);
        if (id !== serial.current) return;
        setModels(value.models);
        const relevant = value.models.filter(m => (compare || m.id === selected) && m.availability !== 'unavailable');
        if (relevant.every(m => m.availability === 'ready')) setState(s => s === 'loading' ? 'generating' : s);
      } catch { /* The generation request supplies its own actionable error. */ }
    }, 1000);
    pollTimer.current = polling;
    setError("");
    setResult(undefined);
    setComparison(undefined);
    try {
      if (compare) {
        const value = await api.compare(settings, controller.signal);
        if (id === serial.current) setComparison(value);
      } else {
        const value = await api.generate(settings, selected, controller.signal);
        if (id === serial.current) setResult(value);
      }
      if (id === serial.current) setState("completed");
    } catch (e) {
      if (id !== serial.current) return;
      if (controller.signal.aborted) setState("canceled");
      else {
        setError(
          e instanceof Error
            ? e.message
            : "Backend unavailable. Check the local service and retry.",
        );
        setState("failed");
      }
    } finally {
      clearInterval(polling);
      if (pollTimer.current === polling) pollTimer.current = null;
      refresh();
    }
  }
  function cancel() {
    if (pollTimer.current) clearInterval(pollTimer.current);
    serial.current++;
    abort.current?.abort();
    setState("canceled");
    setError(
      "Request canceled in the browser. The bounded server worker may still be finishing.",
    );
  }
  function choose(id: ModelID) {
    setSelected(id);
    setResult(undefined);
    setError("");
    setState("idle");
  }
  const busy = state === "generating" || state === 'loading';
  const controlsDisabled = busy || connection === "checking";
  const active = models.find((m) => m.id === selected)!;
  return (
    <section
      className={compare ? "studio comparison-studio" : "studio"}
      id="studio"
    >
      <div className="section-top">
        <div>
          <span className="eyebrow">
            {compare ? "02 / THE COMPARISON LAB" : "01 / THE WRITING STUDIO"}
          </span>
          <h2>
            {compare
              ? "One prompt. Three perspectives."
              : "Give the story a beginning."}
          </h2>
        </div>
        <div className={`connection ${connection}`} aria-live="polite">
          <i />
          {connection === "connected"
            ? "Local inference connected"
            : connection === "checking"
              ? "Checking backend…"
              : "Backend unavailable"}
          <button className="text-button" onClick={refresh}>
            Refresh
          </button>
        </div>
      </div>
      {!compare && (
        <div className="model-select" role="group" aria-label="Choose model">
          {models.map((m) => (
            <button
              className={`model-choice ${selected === m.id ? "selected" : ""}`}
              key={m.id}
              onClick={() => choose(m.id)}
              disabled={controlsDisabled}
              aria-pressed={selected === m.id}
            >
              <span className="model-number">{m.id.toUpperCase()}</span>
              <span>
                <strong>{m.name.replace("NanoLM ", "")}</strong>
                <small>
                  {(m.parameters / 1e6).toFixed(2)}M parameters ·{" "}
                  {m.architecture.n_layers} blocks
                </small>
                <small>
                  {connection === "offline"
                    ? "Availability offline"
                    : connection === "checking"
                      ? "Checking availability"
                      : m.availability === "unavailable"
                        ? "Artifact unavailable"
                        : m.availability === "not_loaded"
                          ? "Loads on request"
                          : "Ready"}
                </small>
              </span>
              <span className="choice-end">
                {m.validation_bpb.toFixed(5)}
                <small>validation BPB</small>
              </span>
            </button>
          ))}
        </div>
      )}
      <div className="workbench">
        <form
          className="input-panel"
          onSubmit={(e) => {
            e.preventDefault();
            submit();
          }}
        >
          <div className="panel-top">
            <label className="eyebrow" htmlFor="prompt">
              YOUR OPENING LINE
            </label>
            <span>128-token model context</span>
          </div>
          <textarea
            id="prompt"
            maxLength={4000}
            value={settings.prompt}
            disabled={controlsDisabled}
            onChange={(e) =>
              setSettings({ ...settings, prompt: e.target.value })
            }
            placeholder="What happens next?"
          />
          <div className="examples">
            <span>Begin with</span>
            {prompts.map((p) => (
              <button
                type="button"
                key={p}
                disabled={controlsDisabled}
                onClick={() => setSettings({ ...settings, prompt: p })}
              >
                {p.trim()}
              </button>
            ))}
          </div>
          <fieldset disabled={controlsDisabled}>
            <legend>Generation settings</legend>
            <div className="settings">
              <label>
                Decoding
                <select
                  value={settings.greedy ? "greedy" : "sample"}
                  onChange={(e) =>
                    setSettings({
                      ...settings,
                      greedy: e.target.value === "greedy",
                    })
                  }
                >
                  <option value="sample">Temperature sampling</option>
                  <option value="greedy">Greedy</option>
                </select>
              </label>
              <label>
                New tokens
                <select
                  value={settings.max_new_tokens}
                  onChange={(e) =>
                    setSettings({
                      ...settings,
                      max_new_tokens: +e.target.value,
                    })
                  }
                >
                  {[64, 128, 256].map((n) => (
                    <option key={n}>{n}</option>
                  ))}
                </select>
              </label>
              <label>
                Temperature <span>{settings.temperature.toFixed(1)}</span>
                <input
                  aria-label="Temperature"
                  type="range"
                  min="0.1"
                  max="2"
                  step="0.1"
                  value={settings.temperature}
                  disabled={controlsDisabled || settings.greedy}
                  onChange={(e) =>
                    setSettings({ ...settings, temperature: +e.target.value })
                  }
                />
              </label>
              <label>
                Seed
                <input
                  type="number"
                  min="0"
                  max="2147483647"
                  placeholder="Random"
                  value={settings.seed ?? ""}
                  onChange={(e) =>
                    setSettings({
                      ...settings,
                      seed: e.target.value === "" ? null : +e.target.value,
                    })
                  }
                />
              </label>
            </div>
          </fieldset>
          <div className="actions">
            <button
              className="primary"
              disabled={
                busy ||
                !settings.prompt.trim() ||
                connection !== "connected" ||
                (!compare && active.availability === "unavailable")
              }
              type="submit"
            >
              {busy
                ? "Generating…"
                : compare
                  ? "Compare all three ↗"
                  : result
                    ? "Regenerate ↗"
                    : "Generate continuation ↗"}
            </button>
            {busy ? (
              <button className="text-button" type="button" onClick={cancel}>
                Cancel
              </button>
            ) : (
              <button
                className="text-button"
                type="button"
                onClick={() => {
                  setSettings({ ...settings, prompt: "" });
                  setResult(undefined);
                  setComparison(undefined);
                  setError("");
                  setState("idle");
                }}
              >
                Clear
              </button>
            )}
          </div>
          <p className="note">
            Built from scratch, trained on Tiny Shakespeare. These are research
            models, not general-purpose assistants.
          </p>
          {connection === "offline" && (
            <p className="offline-note">
              Research metadata is available offline. Start the backend to
              generate real text.
            </p>
          )}
          <span className="sr-only" aria-live="polite">
            {state}
          </span>
        </form>
        {!compare && (
          <Output
            result={result}
            model={active}
            busy={busy}
            loading={state === 'loading'}
            error={
              error ||
              (connection === "connected" &&
              active.availability === "unavailable"
                ? "Verified model artifact unavailable. Check service readiness and retry."
                : undefined)
            }
          />
        )}
      </div>
      {compare && (
        <>
          <div className="comparison-grid">
            {models.map((m) => {
              const slot = comparison?.results.find((r) => r.model_id === m.id);
              return (
                <Output
                  key={m.id}
                  model={m}
                  result={slot?.result || undefined}
                  busy={busy && m.availability !== 'unavailable'}
                  loading={m.availability === 'not_loaded'}
                  error={slot?.error || error || (connection === 'connected' && m.availability === 'unavailable' ? 'Verified model artifact unavailable' : undefined)}
                />
              );
            })}
          </div>
          {comparison && (
            <p className="note">
              Sequential comparison ·{" "}
              {comparison.total_latency_seconds.toFixed(2)} s total · common
              seed {comparison.seed}. Latency is measured, not a model-quality
              score.
            </p>
          )}
        </>
      )}
      <div className="studio-foot">
        <span>NO PRETRAINED WEIGHTS</span>
        <span>NO EXTERNAL LLM CALLS</span>
        <span>UNEDITED MODEL OUTPUT</span>
      </div>
    </section>
  );
}
